const RESOURCE_BY_KEY = new Map(ADMIN_RESOURCES.map((resource) => [resource.key, resource]));

export function getAdminResource(key: string): AdminResource | undefined {
  return RESOURCE_BY_KEY.get(key);
}

/** The relation a field holds, from the resource's own map or the shared defaults. */
export function relationOf(resource: AdminResource, path: string): RelationConfig | undefined {
  const own = resource.relations?.[path];
  if (own) return typeof own === 'string' ? { resource: own } : own;
  const leaf = path.split('.').pop()!;
  // A resource never treats its own display key as a relation (e.g. users.userId does not exist).
  return path === leaf ? DEFAULT_RELATIONS[leaf] : undefined;
}

export interface ReverseRelation {
  /** Resource whose records point at the target. */
  resource: string;
  field: string;
  multiple: boolean;
  valueField: string;
}

/** Every (resource, field) known to point at records of `target`, from the config alone. */
export function declaredReverseRelations(target: string): ReverseRelation[] {
  const found: ReverseRelation[] = [];
  for (const resource of ADMIN_RESOURCES) {
    for (const [field, raw] of Object.entries(resource.relations ?? {})) {
      const relation = typeof raw === 'string' ? { resource: raw } : raw;
      if (relation.resource === target) {
        found.push({
          resource: resource.key,
          field,
          multiple: Boolean(relation.multiple),
          valueField: relation.valueField ?? 'id',
        });
      }
    }
  }
  return found;
}

export function fieldLabel(resource: AdminResource | undefined, path: string): string {
  const override = resource?.fields?.[path]?.label;
  if (override) return override;
  if (FIELD_LABELS[path]) return FIELD_LABELS[path];
  const leaf = path.split('.').pop()!;
  if (FIELD_LABELS[leaf] && path === leaf) return FIELD_LABELS[leaf];
  // "circumferences.biceps" → "Circumferences › Biceps"
  return path
    .split('.')
    .map((part) =>
      (FIELD_LABELS[part] ?? part.replace(/([a-z0-9])([A-Z])/g, '$1 $2')).replace(/^./, (char) => char.toUpperCase())
    )
    .join(' › ');
}

export function optionLabel(resource: AdminResource | undefined, path: string, value: string): string {
  return resource?.fields?.[path]?.optionLabels?.[value] ?? OPTION_LABELS[value] ?? value;
}

/** Schema of one field as the server derives it from the Mongoose model. */
export interface FieldMeta {
  path: string;
  kind: 'string' | 'number' | 'boolean' | 'date' | 'stringList' | 'numberList' | 'objectList' | 'json';
  required: boolean;
  enum?: string[];
  /** Field names of one item of an `objectList`, as a hint for the JSON editor. */
  itemFields?: string[];
  readOnly: boolean;
}
