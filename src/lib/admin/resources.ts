export interface RelationConfig {
  /** Key of the resource the field points at. */
  resource: string;
  /** The field holds a list of references. */
  multiple?: boolean;
  /** Field of the target stored in this field; `id` unless the link is by name. */
  valueField?: string;
}

export type FieldWidget = 'textarea' | 'richtext' | 'image' | 'images' | 'json' | 'password' | 'url' | 'color';

export interface FieldOverride {
  label?: string;
  widget?: FieldWidget;
  help?: string;
  /** Left out of the form (still visible in the raw JSON view). */
  hidden?: boolean;
  readOnly?: boolean;
  optionLabels?: Record<string, string>;
}

export interface AdminResource {
  /** Key used in URLs and the API. */
  key: string;
  label: string;
  singular: string;
  group: AdminGroupKey;
  /** Name of a lucide icon (resolved in components/admin/resource/icons). */
  icon: string;
  description: string;
  /** Fields tried in order to name a record. */
  title: string[];
  subtitle?: string;
  /** Fields matched by the search box. */
  search: string[];
  sort: [string, 1 | -1];
  /** Columns of the list, besides the record's name. */
  columns: string[];
  relations?: Record<string, RelationConfig | string>;
  fields?: Record<string, FieldOverride>;
  /** Never sent to the browser and never writable. */
  secret?: string[];
  /** Shown but not editable (values the server computes). */
  readOnly?: string[];
  /** Left out of list responses (large fields). */
  heavy?: string[];
  /** A dedicated screen with a richer editor for this resource. */
  page?: { href: string; label: string };
  canCreate?: boolean;
  note?: string;
}

